"""Generates test positions by self-play with the engine (no external data).

  python scripts/make_positions.py suite    > tests/search/suite.epd
  python scripts/make_positions.py openings > tests/search/openings.epd

suite:    50 positions for time-to-depth benchmarks: 15 openings, 20
          middlegames and 15 endgames, from games that start with random
          moves and continue with a fixed-depth CPU search.
openings: 200 balanced start positions for engine matches: 8 random plies,
          kept if a depth-6 search scores them within 60 centipawns.

Everything is seeded, so the same engine build gives the same files.
"""

import pathlib
import random
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINE = ROOT / "build" / "Release" / "chessgpu.exe"
START = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"


class Engine:
    def __init__(self):
        self.p = subprocess.Popen([str(ENGINE), "uci"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True,
                                  bufsize=1)
        self.send("uci")
        self.wait("uciok")
        self.send("setoption name Search value cpu")
        self.send("isready")
        self.wait("readyok")

    def send(self, line):
        self.p.stdin.write(line + "\n")
        self.p.stdin.flush()

    def wait(self, prefix):
        lines = []
        while True:
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("engine exited")
            line = line.strip()
            lines.append(line)
            if line.startswith(prefix):
                return lines

    def position(self, moves):
        self.send("position startpos" + (" moves " + " ".join(moves) if moves else ""))

    def fen(self):
        self.send("d")
        return self.wait("info string fen ")[-1][len("info string fen "):]

    def legal_moves(self):
        self.send("legalmoves")
        return self.wait("info string legalmoves")[-1].split()[3:]

    def search(self, depth):
        """Returns (best move, score in centipawns or None for mate scores)."""
        self.send(f"go depth {depth}")
        lines = self.wait("bestmove")
        best = lines[-1].split()[1]
        score = None
        for line in lines:
            parts = line.split()
            if line.startswith("info depth") and "score" in parts:
                i = parts.index("score")
                score = int(parts[i + 2]) if parts[i + 1] == "cp" else None
        return best, score

    def close(self):
        self.send("quit")
        self.p.wait()


def piece_count(fen):
    return sum(c.isalpha() for c in fen.split()[0])


def random_opening(engine, rng, plies):
    moves = []
    for _ in range(plies):
        engine.position(moves)
        legal = engine.legal_moves()
        if not legal:
            return None
        moves.append(rng.choice(legal))
    return moves


def suite(engine):
    rng = random.Random(0x135288B)
    out = []
    want = {"opening": 15, "middlegame": 20, "endgame": 15}
    have = {k: 0 for k in want}
    game = 0
    while any(have[k] < want[k] for k in want):
        game += 1
        moves = random_opening(engine, rng, rng.randint(6, 10))
        if moves is None:
            continue
        engine.position(moves)
        if have["opening"] < want["opening"]:
            out.append((engine.fen(), f"opening, game {game}"))
            have["opening"] += 1
            continue
        taken_middle = False
        for ply in range(len(moves), 200):
            engine.position(moves)
            fen = engine.fen()
            best, score = engine.search(4)
            if best == "(none)":
                break
            balanced = score is not None and abs(score) < 300
            if (not taken_middle and have["middlegame"] < want["middlegame"] and 20 <= ply <= 40 and balanced
                    and rng.random() < 0.15):
                out.append((fen, f"middlegame, game {game}, ply {ply}"))
                have["middlegame"] += 1
                taken_middle = True
            if have["endgame"] < want["endgame"] and piece_count(fen) <= 12 and balanced:
                out.append((fen, f"endgame, game {game}, ply {ply}"))
                have["endgame"] += 1
                break
            moves.append(best)
    print("# Time-to-depth benchmark positions, generated by scripts/make_positions.py suite")
    for fen, comment in out:
        print(f"{fen} ; {comment}")


def openings(engine):
    rng = random.Random(8675309)
    seen = set()
    count = 0
    print("# Balanced match openings, generated by scripts/make_positions.py openings")
    while count < 200:
        moves = random_opening(engine, rng, 8)
        if moves is None:
            continue
        engine.position(moves)
        fen = engine.fen()
        key = " ".join(fen.split()[:4])
        if key in seen:
            continue
        _, score = engine.search(6)
        if score is None or abs(score) >= 60:
            continue
        seen.add(key)
        count += 1
        print(f"{fen} ; {' '.join(moves)} ; score {score}")


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("suite", "openings"):
        print(__doc__)
        sys.exit(2)
    engine = Engine()
    try:
        suite(engine) if sys.argv[1] == "suite" else openings(engine)
    finally:
        engine.close()


if __name__ == "__main__":
    main()
